"""Mandate constraint evaluation, attenuation (scope narrowing) checks and risk tiering."""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class TxRequest:
    merchant_id: str
    action: str
    amount: int
    currency: str
    category: str | None = None


@dataclass
class Usage:
    period_spent: int = 0
    tx_count: int = 0
    known_merchant: bool = False


def _merchant_allowed(constraints: dict, merchant_id: str) -> bool:
    merchants = constraints.get("merchants", {})
    if merchant_id in merchants.get("deny", []):
        return False
    allow = merchants.get("allow")
    return allow is None or "*" in allow or merchant_id in allow


def check_constraints(actions: list[str], constraints: dict, tx: TxRequest, usage: Usage) -> list[str]:
    """Return the list of violated constraint names (empty = within mandate)."""
    v = []
    if tx.action not in actions:
        v.append("action")
    if tx.currency != constraints.get("currency"):
        v.append("currency")
    if not _merchant_allowed(constraints, tx.merchant_id):
        v.append("merchants")
    cat_allow = constraints.get("categories", {}).get("allow")
    if cat_allow is not None and tx.category not in cat_allow:
        v.append("categories")
    period = constraints.get("max_amount_per_period")
    if period and usage.period_spent + tx.amount > period["amount"]:
        v.append("max_amount_per_period")
    if "max_tx_count" in constraints and usage.tx_count + 1 > constraints["max_tx_count"]:
        v.append("max_tx_count")
    # Hard ceiling even with step-up; amounts between stepup_over_amount and this trigger step-up (risk_tier).
    if tx.amount > constraints.get("max_amount_per_tx", tx.amount):
        v.append("max_amount_per_tx")
    return v


def risk_tier(constraints: dict, tx: TxRequest, usage: Usage, operator_tier: str) -> tuple[str, float]:
    """Simplified PRD §5 policy. Returns (tier, score)."""
    presence = constraints.get("human_presence", "not_required")
    threshold = constraints.get("stepup_over_amount")
    if presence == "always":
        return "high", 0.8
    if threshold is not None and tx.amount > threshold:
        return "high", 0.75
    if operator_tier == "registered":
        return "high", 0.7
    if not usage.known_merchant:
        return "medium", 0.4
    return "low", 0.1


def _subset(child: list | None, parent: list | None) -> bool:
    if parent is None or "*" in parent:
        return True
    if child is None or "*" in child:
        return False
    return set(child) <= set(parent)


def attenuation_violations(parent_actions, parent_c: dict, child_actions, child_c: dict) -> list[str]:
    """Child mandate must be at least as strict as its parent on every dimension."""
    v = []
    if not set(child_actions) <= set(parent_actions):
        v.append("actions")
    if child_c.get("currency") != parent_c.get("currency"):
        v.append("currency")
    for key in ("max_amount_per_tx", "max_tx_count", "stepup_over_amount"):
        if key in parent_c and child_c.get(key, float("inf")) > parent_c[key]:
            v.append(key)
    if "max_amount_per_period" in parent_c:
        cp = child_c.get("max_amount_per_period")
        if not cp or cp["amount"] > parent_c["max_amount_per_period"]["amount"] or cp["period"] != parent_c["max_amount_per_period"]["period"]:
            v.append("max_amount_per_period")
    if not _subset(child_c.get("merchants", {}).get("allow"), parent_c.get("merchants", {}).get("allow")):
        v.append("merchants.allow")
    if not set(parent_c.get("merchants", {}).get("deny", [])) <= set(child_c.get("merchants", {}).get("deny", [])):
        v.append("merchants.deny")
    if not _subset(child_c.get("categories", {}).get("allow"), parent_c.get("categories", {}).get("allow")):
        v.append("categories")
    order = ["not_required", "required_over_amount", "always"]
    if order.index(child_c.get("human_presence", "not_required")) < order.index(parent_c.get("human_presence", "not_required")):
        v.append("human_presence")
    return v


def consent_summary(operator_name: str, actions: list[str], c: dict) -> str:
    """Human-readable summary generated by AgentPass from constraints (never supplied by the agent, T14)."""
    parts = [f"{operator_name} 에이전트에게 다음 권한을 위임합니다: {', '.join(actions)}."]
    cur = c.get("currency", "")
    if "max_amount_per_tx" in c:
        parts.append(f"1회 최대 {c['max_amount_per_tx']:,} {cur}.")
    if "max_amount_per_period" in c:
        parts.append(f"기간({c['max_amount_per_period']['period']}) 누적 최대 {c['max_amount_per_period']['amount']:,} {cur}.")
    if "stepup_over_amount" in c:
        parts.append(f"{c['stepup_over_amount']:,} {cur} 초과 시 매번 본인 승인 필요.")
    if c.get("categories", {}).get("allow"):
        parts.append(f"카테고리: {', '.join(c['categories']['allow'])}.")
    allow = c.get("merchants", {}).get("allow")
    parts.append(f"상점: {'전체' if not allow or '*' in allow else ', '.join(allow)}.")
    return " ".join(parts)
